const MESSAGES: Record<string, DigitalCardsMessages> = { en, it, de }

/** The dashboard languages these messages cover. */
export const DIGITAL_CARDS_MESSAGE_LOCALES = ['en', 'it', 'de'] as const

export function getDigitalCardsMessages(locale: string | null | undefined): DigitalCardsMessages {
  const base = typeof locale === 'string' ? locale.toLowerCase().split('-')[0] : ''
  return MESSAGES[base] ?? en
}

/** Fills {placeholders}; an unknown placeholder is left as written. */
export function formatDigitalCardsMessage(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m))
}

/** The error text for an action code (unknown codes → "failed"). */
export function digitalCardErrorText(m: DigitalCardsMessages, code: string): string {
  return (m.errors as Record<string, string>)[code] ?? m.errors.failed
}

/** The name of a statistics source (unknown tags are shown as written). */
export function digitalCardSourceName(m: DigitalCardsMessages, source: string): string {
  return (m.sources as Record<string, string>)[source] ?? source
}

